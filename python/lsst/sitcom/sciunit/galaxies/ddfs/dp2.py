class DeepFieldInfoDp2(pydantic.BaseModel):
    """Assorted useful properties for deep fields."""

    model_config: ClassVar[pydantic.ConfigDict] = arbitrary_allowed_config

    limits_dec: tuple[float | None, float | None] = pydantic.Field(
        title="Declination limits for sky plots",
        default=(None, None),
    )
    limits_ra: tuple[float | None, float | None] = pydantic.Field(
        title="RA limits for sky plots",
        default=(None, None),
    )
    metrics_plot_band: dict[str, dict[str, dict[str, float]]] = pydantic.Field(
        title="Dict by band of dicts by metric suffix with key-value pairs relevant for plots of that metric."
    )
    refcat_names: list[str] = pydantic.Field(
        title="Dataset type names for useful external reference catalogs",
    )
    tract_patches: dict[int, None | tuple[int, ...]] = pydantic.Field(
        title="Dict of patches by tract which have enough coverage to at"
        " least attempt to measure most useful metrics",
    )

    def apply(self, action: PerPatchPropertyMapPlot, band):
        for metric, overrides in self.metrics_plot_band[band].items():
            if (config := action.metrics.get(metric)) is not None:
                for attr, value in overrides.items():
                    setattr(config, attr, value)
        if (limit := self.limits_ra[0]) is not None:
            action.ra_min = limit
        if (limit := self.limits_ra[1]) is not None:
            action.ra_max = limit
        if (limit := self.limits_dec[0]) is not None:
            action.dec_min = limit
        if (limit := self.limits_dec[1]) is not None:
            action.dec_max = limit


